"""build/words.json -> pipeline/gfx/data.js (word times + caption chunks).

Applies transcript corrections (brand spelling, apostrophes, homophones the
recogniser got wrong) and groups words into short caption chunks: at most
5 words / 30 characters, broken at punctuation and at every cut.
"""
import json

words = json.load(open("build/words.json"))
cl = json.load(open("build/cutlist.json"))

FIX = {
    "it,": "it.",
    "answer's": "answers",
    "site.": "cite.",
    "gaps,": "gaps.",
    "description,": "description.",
    "page,": "page.",
    "missing,": "missing.",
    "with.": "with.",
}
# Move words Whisper placed inside a graphic-only gap onto the next line.
for w in words:
    if cl["segments"][w["seg"]].get("gap"):
        w["seg"] += 1
        w["s"] = max(w["s"], cl["segments"][w["seg"]]["edit_f0"] / 30 + 0.02)
first_comp = next(i for i, w in enumerate(words) if w["w"] == "competitors")
words[first_comp]["w"] = "competitor's"
out = []
for w in words:
    t = FIX.get(w["w"], w["w"])
    if t.startswith(".") and out:  # "seekworthy" ".ai," -> one token
        out[-1]["w"] += t.rstrip(",") + ("" if t.endswith(".") else "")
        out[-1]["e"] = w["e"]
        continue
    out.append(dict(w=t, s=w["s"], e=w["e"], seg=w["seg"]))
for w in out:
    if w["w"] == "seekworthy.ai":
        w["w"] = "seekworthy.ai."

# A word whose start drifted into the previous segment starts with its own.
for w in out:
    seg = cl["segments"][w["seg"]]
    w["s"] = max(w["s"], seg["edit_f0"] / 30 + 0.02)

# Caption chunks, written by hand: the words must match the transcript
# token for token; punctuation and case come from here.
CHUNKS = """
Your next customer | could ask AI | for a recommendation | and never hear your name. |
They ask ChatGPT | which company to work with. | It gives them a shortlist. |
Your competitor's on it. | You're not. | Would you know? |
I'm Ben, | founder of Seekworthy. | We help businesses see | how they show up | in AI answers. |
But when a buyer | asks AI for advice, | you need to know | if you show up | as part of the answer. |
That's why we built | Seekworthy. | It helps you understand | how your business shows up | across AI platforms. |
You start with your website | and review the questions | that your buyers | are likely to ask. |
Seekworthy checks | those questions | and shows you where | your brand gets mentioned. |
It also shows | which competitors appear | and which sources | the answers cite. |
So you can go beyond | checking your name once | and hoping that tells | the whole story. |
You've got to check | and fix the gaps. | Correct an inaccurate description. | Improve a page. |
Create content | that answers a question | you've been missing. | And check again | to see what's changed. |
No one can promise you | a place in every AI answer. |
The point is to stop guessing | and to start working | from evidence. |
Go to seekworthy.ai. | Enter your website | and start with a free check. | No card needed. |
Find out whether AI | is recommending | your business.
"""


def norm(x):
    return "".join(ch for ch in x.lower() if ch.isalnum())


chunks = []
k = 0
for part in CHUNKS.replace("\n", " ").split("|"):
    toks = part.split()
    if not toks:
        continue
    grp = []
    for tok in toks:
        assert norm(out[k]["w"]) == norm(tok), (k, out[k]["w"], tok)
        grp.append(dict(out[k], w=tok, k=k))
        k += 1
    chunks.append(grp)
assert k == len(out), (k, len(out))
caps = []
for i, c in enumerate(chunks):
    s = c[0]["s"] - 0.05
    nxt = chunks[i + 1][0]["s"] - 0.05 if i + 1 < len(chunks) else 1e9
    seg_end = cl["segments"][c[-1]["seg"]]["edit_f1"] / 30
    e = min(nxt, max(c[-1]["e"] + 0.35, s + 0.6), seg_end + 0.25)
    caps.append(dict(t=" ".join(x["w"] for x in c), s=round(s, 3), e=round(e, 3), i=c[0]["k"]))

open("pipeline/gfx/data.js", "w").write(
    "// generated by pipeline/gfx_data.py\nwindow.WORDS = " + json.dumps(out) + ";\nwindow.CAPTIONS = "
    + json.dumps(caps, indent=0) + ";\nwindow.TOTAL_FRAMES = " + str(cl["frames"]) + ";\n")
for c in caps:
    print(f"{c['s']:6.2f}-{c['e']:6.2f} {c['t']}")
